-- B03: content-fingerprint progress detection.
--
-- The repeat guard compared a file write's byte COUNT, so two different edits
-- of the same length collided and a productive equal-length edit was wrongly
-- blocked. Record a content hash (sha256 hex of the written bytes) so the
-- guard can tell a real change from an identical rewrite. Append-only and
-- nullable: existing rows read NULL (treated as "no hash recorded" — the guard
-- falls back to not matching, i.e. it never blocks on a missing hash).
--
-- Privacy: this is a HASH, never the file contents; the activity ledger still
-- does not store what was written.
alter table "build_activity" add column "contentHash" text;
