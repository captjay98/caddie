/**
 * Generated schema (plan part B — "Generated schema").
 *
 * For big apps, and for any app that declares a team or an `admin` route, the
 * host generates `migrations/0001_schema.sql` from the architecture block
 * instead of letting a builder write migrations. With all modules sharing one
 * schema, parallel builders never collide on migration numbers, and in big
 * apps the schema is fixed once approved.
 *
 * `needsGeneratedSchema(block, kind)` says whether a block gets one, and
 * `generateSchema(block)` returns the SQL. The output is DETERMINISTIC: tables
 * in declaration order, columns in a fixed order, and index names derived from
 * table and column — the same block always yields byte-identical SQL, so part
 * B's snapshot test is stable.
 */

import type { ArchitectureBlock, ArchitectureTable, FieldType } from '@caddie/contracts';

export type SchemaKind = 'small' | 'big';

/**
 * A generated schema is written for a big app, or for any app that declares a
 * team or an `admin` route (part B). Other small apps keep builder-written
 * migrations.
 */
export function needsGeneratedSchema(block: ArchitectureBlock, kind: SchemaKind): boolean {
	if (kind === 'big') return true;
	if (block.team !== null) return true;
	return block.routes.some((r) => r.access === 'admin');
}

/** The SQL column type for a declared field type (part B). */
function columnType(type: FieldType): string {
	switch (type) {
		case 'integer':
		case 'boolean': // stored as integer 0/1
			return 'integer';
		case 'real':
			return 'real';
		case 'text':
		case 'datetime': // ISO text
		case 'json': // text
		case 'file': // a file-id text
			return 'text';
	}
}

/** A table gets an `ownerId` column (person-owned) or a `teamId` column (team-owned). */
function ownerColumn(table: ArchitectureTable): 'ownerId' | 'teamId' | null {
	if (table.owner === 'person') return 'ownerId';
	if (table.owner === 'team') return 'teamId';
	return null;
}

interface IndexSpec {
	readonly name: string;
	readonly table: string;
	readonly column: string;
}

function createTableSql(table: ArchitectureTable, indexes: IndexSpec[]): string {
	const lines: string[] = ['  id text primary key'];
	const owner = ownerColumn(table);
	if (owner) {
		lines.push(`  ${owner} text not null`);
		indexes.push({ name: `ix_${table.name}_${owner}`, table: table.name, column: owner });
	}
	// Declared fields, in declaration order.
	for (const field of table.fields) {
		lines.push(`  ${field.name} ${columnType(field.type)}`);
		if (field.references) {
			indexes.push({ name: `ix_${table.name}_${field.name}`, table: table.name, column: field.name });
		}
	}
	// Timestamps on every table.
	lines.push('  createdAt text not null');
	lines.push('  updatedAt text not null');
	// Declared references become foreign keys, in field order.
	for (const field of table.fields) {
		if (field.references) {
			lines.push(`  foreign key (${field.name}) references ${field.references}(id)`);
		}
	}
	return `create table ${table.name} (\n${lines.join(',\n')}\n);`;
}

/**
 * Generate `migrations/0001_schema.sql` from the block's tables, plus the
 * platform tables every team/admin app needs. Deterministic: declaration
 * order for tables and fields, and a fixed order for the platform tables and
 * the indexes (grouped by table, in table order, then owner/reference order).
 */
export function generateSchema(block: ArchitectureBlock): string {
	const indexes: IndexSpec[] = [];
	const parts: string[] = [];

	parts.push('-- Generated by Caddie from the approved "How your app works" block. Do not edit.');
	parts.push('-- One schema for every part of the app, so parallel builders never collide.');

	// App tables, in declaration order.
	for (const table of block.tables) {
		parts.push(createTableSql(table, indexes));
	}

	// Platform tables (part B). team_members only when the app has a team.
	if (block.team) {
		parts.push(
			[
				'create table team_members (',
				'  teamId text not null,',
				'  personId text not null,',
				'  role text not null,',
				'  createdAt text not null,',
				'  primary key (teamId, personId)',
				');',
			].join('\n'),
		);
	}
	parts.push(['create table caddie_admins (', '  personId text primary key,', '  createdAt text not null', ');'].join('\n'));

	// Indexes last, deterministic order (already grouped by table in table order).
	for (const ix of indexes) {
		parts.push(`create index ${ix.name} on ${ix.table}(${ix.column});`);
	}
	if (block.team) {
		parts.push('create index ix_team_members_personId on team_members(personId);');
	}

	return parts.join('\n\n') + '\n';
}
