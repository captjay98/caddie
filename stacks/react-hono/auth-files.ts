/** Better Auth's returned headers are not always a real Headers object: read Set-Cookie either way. */
function setCookiesOf(headers: unknown): string[] {
  if (!headers || typeof headers !== "object") return [];
  const own = headers as { getSetCookie?: () => string[] };
  if (typeof own.getSetCookie === "function") {
    const list = own.getSetCookie();
    if (list.length > 0) return list;
  }
  if (typeof (headers as Iterable<unknown>)[Symbol.iterator] !== "function") return [];
  const found: string[] = [];
  for (const pair of headers as Iterable<[string, string]>) {
    if (Array.isArray(pair) && String(pair[0]).toLowerCase() === "set-cookie") found.push(String(pair[1]));
  }
  return found;
}

/**
 * A JSON answer that carries cookies. Built here rather than with c.header(),
 * which silently drops Set-Cookie once the request already has a response.
 */
function jsonWithCookies(body: unknown, cookies: string[], status = 200): Response {
  const headers = new Headers({ "content-type": "application/json" });
  for (const cookie of cookies) headers.append("set-cookie", cookie);
  return new Response(JSON.stringify(body), { status, headers });
}

/** Refuse a request another site's page sent (SameSite cookies already stop most). */
function sameOrigin(c: Context) {
  const origin = c.req.header("origin");
  if (origin && origin !== new URL(c.req.url).origin) throw fail(403, "This request came from another site.");
}

async function readBody(c: Context): Promise<Record<string, unknown>> {
  if (!(c.req.header("content-type") ?? "").toLowerCase().startsWith("application/json")) throw fail(415, "Send JSON.");
  try {
    const body = (await c.req.json()) as unknown;
    return body && typeof body === "object" ? (body as Record<string, unknown>) : {};
  } catch {
    throw fail(400, "Send JSON.");
  }
}

function readEmail(value: unknown): string {
  const email = typeof value === "string" ? value.trim().toLowerCase() : "";
  if (email.length > 254 || !EMAIL.test(email)) throw fail(400, "Enter a valid email address.");
  return email;
}

