/** The session behind this request, with any cookie Better Auth wants refreshed. */
async function sessionOf(c: Context): Promise<{ user: AppUser | null; cookies: string[] }> {
  if ((envOf(c)?.CADDIE_AUTH_SECRET ?? "").length < 32) return { user: null, cookies: [] };
  const result = await authFor(c).api.getSession({ headers: c.req.raw.headers, returnHeaders: true });
  return { user: result.response?.user ? toUser(result.response.user) : null, cookies: setCookiesOf(result.headers) };
}

/** The person signed in on this request, or null. */
export async function currentUser(c: Context): Promise<AppUser | null> {
  return (await sessionOf(c)).user;
}

/** The person signed in on this request; answers 401 when nobody is. */
export async function requireUser(c: Context): Promise<AppUser> {
  const user = await currentUser(c);
  if (!user) throw fail(401, "Sign in first.");
  return user;
}

/** Add the sign-in routes under the app's /api. Call once in src/server.ts. */
export function mountSignIn<E extends { Bindings: SignInEnv }>(app: Hono<E>): void {
  // 1. Email a 6-digit code. Only the newest code works.
  app.post("/auth/code", async (c) => {
    sameOrigin(c);
    const email = readEmail((await readBody(c)).email);
    const auth = authFor(c);
    const context = await auth.$context;
    const identifier = "sign-in-otp-" + email;
    await context.internalAdapter.deleteVerificationByIdentifier(identifier);
    const code = await auth.api.createVerificationOTP({ body: { email, type: "sign-in" } });
    const sent = await envOf(c).CADDIE.signInCode({ email, code });
    if (!sent.ok) {
      await context.internalAdapter.deleteVerificationByIdentifier(identifier);
      return c.json({ error: sent.message }, sent.reason === "busy" ? 429 : 503);
    }
    return c.json({ sent: true });
  });

  // 2. Trade the code for a session cookie. A new email address becomes a new user.
  app.post("/auth/sign-in", async (c) => {
    sameOrigin(c);
    const body = await readBody(c);
    const email = readEmail(body.email);
    const code = typeof body.code === "string" ? body.code.trim() : "";
    if (!/^\d{6}$/.test(code)) throw fail(400, "Enter the 6-digit code from the email.");
    try {
      const result = await authFor(c).api.signInEmailOTP({ body: { email, otp: code }, headers: c.req.raw.headers, returnHeaders: true });
      return jsonWithCookies({ user: toUser(result.response.user) }, setCookiesOf(result.headers));
    } catch (error) {
      const known = CODE_ERRORS[String((error as { body?: { code?: unknown } })?.body?.code ?? "")];
      if (known) throw fail(known[0], known[1]);
      throw error;
    }
  });

  app.post("/auth/sign-out", async (c) => {
    sameOrigin(c);
    let cookies: string[] = [];
    if ((envOf(c)?.CADDIE_AUTH_SECRET ?? "").length >= 32) {
      const result = await authFor(c)
        .api.signOut({ headers: c.req.raw.headers, returnHeaders: true })
        .catch(() => null);
      cookies = setCookiesOf(result?.headers);
    }
    return jsonWithCookies({ signedOut: true }, cookies);
  });

  app.get("/auth/me", async (c) => {
    const { user, cookies } = await sessionOf(c);
    return jsonWithCookies({ user }, cookies);
  });
}
