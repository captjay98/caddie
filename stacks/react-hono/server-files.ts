/**
 * The backend half of the react-hono scaffold (Publish programme, stage 2):
 * every generated app is backend-ready FROM THE START.
 *
 *   src/server.ts               the app's server (Hono, routes under /api) —
 *                               the builder edits it.
 *   caddie/d1.ts                Cloudflare D1 types (protected).
 *   caddie/ai.ts                env.CADDIE.ai() types and how to use them —
 *                               Caddie's AI, no key (protected).
 *   caddie/check-server.ts      fails the build when the server bundle uses
 *                               something Cloudflare Workers lacks (protected).
 *   test/setup/d1.ts            a D1 database over bun:sqlite for tests, with
 *                               every migrations/*.sql applied (protected).
 *   test/setup/ai.ts            createTestAi(): env.CADDIE for tests, no
 *                               network, no cost (protected).
 *   (sign-in: stacks/react-hono/auth-files.ts)
 *   test/examples/server.example.test.ts
 *                               how to test a route; outside src/, so it never
 *                               counts toward the host's `bun test src/` gate.
 *
 * The same `env.DB` code runs in three places: tests (test/setup/d1.ts), the
 * preview (Caddie's PreviewDatabase, server/preview-runtime.ts) and the
 * published app (the app's real D1 database).
 */

