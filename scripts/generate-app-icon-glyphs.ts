#!/usr/bin/env bun
/**
 * Draw the letters for published apps' home-screen icons (plan step 2.4)
 * with the Chromium that Playwright already installs for the browser tests:
 *
 *   bun scripts/generate-app-icon-glyphs.ts
 *
 * Renders A-Z and 0-9 in Inter Bold (@fontsource/inter, SIL Open Font
 * License 1.1) on a 512 canvas: each glyph's ink centred horizontally and the
 * capital band (CAP pixels tall) centred vertically. Each glyph's coverage
 * (one byte per pixel), cropped to its ink and deflated, goes to
 * apps/app/src/server/app-icon-glyphs.ts; app-icons.ts scales it to every
 * icon size when an app is published. Nothing here runs in production, and
 * the output only changes when this script is re-run on purpose.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { deflateSync } from 'node:zlib';
import { chromium } from '@playwright/test';

const ROOT = join(import.meta.dir, '..');
const FONT_PACKAGE = join(ROOT, 'apps', 'app', 'node_modules', '@fontsource', 'inter');
const FONT = join(FONT_PACKAGE, 'files', 'inter-latin-700-normal.woff2');
const OUT = join(ROOT, 'apps', 'app', 'src', 'server', 'app-icon-glyphs.ts');
const CANVAS = 512;
const CAP = 240;
const CHARS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';

const fontVersion = JSON.parse(readFileSync(join(FONT_PACKAGE, 'package.json'), 'utf8')).version as string;

type Drawn = { x: number; y: number; w: number; h: number; alpha: string };

const browser = await chromium.launch();
let drawn: Record<string, Drawn>;
try {
	const page = await browser.newPage();
	await page.setContent('<!doctype html><html><body></body></html>');
	drawn = await page.evaluate(
		async ({ fontBase64, size, cap, chars }) => {
			const bytes = Uint8Array.from(atob(fontBase64), (c) => c.charCodeAt(0));
			const face = new FontFace('CaddieIconInter', bytes.buffer, { weight: '700' });
			await face.load();
			document.fonts.add(face);
			const canvas = document.createElement('canvas');
			canvas.width = size;
			canvas.height = size;
			const ctx = canvas.getContext('2d', { willReadFrequently: true })!;
			ctx.font = '700 100px CaddieIconInter';
			const capPerPx = ctx.measureText('H').actualBoundingBoxAscent / 100;
			ctx.font = `700 ${cap / capPerPx}px CaddieIconInter`;
			ctx.textAlign = 'left';
			ctx.textBaseline = 'alphabetic';
			const baseline = size / 2 + cap / 2;
			const out: Record<string, { x: number; y: number; w: number; h: number; alpha: string }> = {};
			for (const ch of chars) {
				ctx.clearRect(0, 0, size, size);
				const m = ctx.measureText(ch);
				ctx.fillStyle = '#000';
				ctx.fillText(ch, size / 2 - (m.actualBoundingBoxRight - m.actualBoundingBoxLeft) / 2, baseline);
				const data = ctx.getImageData(0, 0, size, size).data;
				let minX = size;
				let minY = size;
				let maxX = -1;
				let maxY = -1;
				for (let y = 0; y < size; y++) {
					for (let x = 0; x < size; x++) {
						if (data[(y * size + x) * 4 + 3] === 0) continue;
						if (x < minX) minX = x;
						if (x > maxX) maxX = x;
						if (y < minY) minY = y;
						if (y > maxY) maxY = y;
					}
				}
				if (maxX < 0) throw new Error(`nothing drawn for ${ch}`);
				const w = maxX - minX + 1;
				const h = maxY - minY + 1;
				let binary = '';
				for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) binary += String.fromCharCode(data[((minY + y) * size + minX + x) * 4 + 3]!);
				out[ch] = { x: minX, y: minY, w, h, alpha: btoa(binary) };
			}
			return out;
		},
		{ fontBase64: readFileSync(FONT).toString('base64'), size: CANVAS, cap: CAP, chars: CHARS },
	);
} finally {
	await browser.close();
}

const lines = Object.entries(drawn).map(([ch, g]) => {
	const packed = deflateSync(Buffer.from(g.alpha, 'base64'), { level: 9 }).toString('base64');
	return `\t${ch.match(/\d/) ? `'${ch}'` : ch}: { x: ${g.x}, y: ${g.y}, w: ${g.w}, h: ${g.h}, data: '${packed}' },`;
});
writeFileSync(
	OUT,
	[
		'// GENERATED by scripts/generate-app-icon-glyphs.ts. Do not edit by hand; re-run the script.',
		`// Inter Bold (@fontsource/inter ${fontVersion}, SIL Open Font License 1.1), A-Z and 0-9: each glyph's`,
		`// coverage (one byte per pixel, row by row), cropped to its ink and zlib-deflated, drawn on a`,
		`// ${CANVAS}x${CANVAS} canvas with its ink centred horizontally and the ${CAP}px capital band centred vertically.`,
		'',
		`export const GLYPH_CANVAS = ${CANVAS};`,
		`export const GLYPH_CAP = ${CAP};`,
		'',
		'export interface Glyph {',
		'\t/** Top-left of the cropped ink on the canvas. */',
		'\tx: number;',
		'\ty: number;',
		'\tw: number;',
		'\th: number;',
		'\t/** base64 of the deflated coverage bytes (w*h). */',
		'\tdata: string;',
		'}',
		'',
		'export const GLYPHS: Readonly<Record<string, Glyph>> = {',
		...lines,
		'};',
		'',
	].join('\n'),
);
const bytes = readFileSync(OUT).length;
console.log(`wrote apps/app/src/server/app-icon-glyphs.ts: ${Object.keys(drawn).length} glyphs, ${Math.round(bytes / 1024)} KB`);
