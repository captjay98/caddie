import { describe, expect, test } from 'bun:test';
import { cpSync, existsSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawn, spawnSync, type ChildProcess } from 'node:child_process';

/**
 * P15c live FastAPI + React journey — the REAL template flow behind explicit
 * toolchain gates:
 *
 *   1. CADDIE_LIVE_AUTHORIZED=1 (uv sync fetches from the Python package
 *      index — an external effect plain `bun test` never triggers),
 *   2. uv + python + bun present on PATH (toolchains are never installed by
 *      this suite; a missing tool is a named BLOCKED),
 *
 * and only then the recipe commands for real: uv sync → uv run pytest →
 * bun install → bun run build (client dist emitted) →
 * uv run uvicorn app.main:app, asserting the health probe and a real
 * create-then-read round trip over HTTP. A phase failure fails here.
 */

const authorized = process.env.CADDIE_LIVE_AUTHORIZED === '1';
const REPO = join(import.meta.dir, '..', '..', '..');
const TEMPLATE = join(REPO, 'stacks', 'fastapi-react', 'template');
const PORT = 8799;

function missingTools(): string[] {
	const missing: string[] = [];
	for (const tool of ['uv', 'python3', 'bun']) {
		if (!Bun.which(tool)) missing.push(tool);
	}
	return missing;
}

function run(argv: string[], cwd: string): { code: number; output: string } {
	const proc = spawnSync(argv[0], argv.slice(1), { cwd, encoding: 'utf8' });
	return { code: proc.status ?? 1, output: `${proc.stdout}${proc.stderr}` };
}

async function waitForServer(url: string, timeoutMs: number): Promise<Response> {
	const deadline = Date.now() + timeoutMs;
	let lastError = 'no attempt';
	while (Date.now() < deadline) {
		try {
			const res = await fetch(url);
			if (res.status < 500) return res;
			lastError = `status ${res.status}`;
		} catch (error) {
			lastError = String(error);
		}
		await new Promise((resolve) => setTimeout(resolve, 250));
	}
	throw new Error(`uvicorn never answered on ${url}: ${lastError}`);
}

describe('P15c live FastAPI + React journey (BLOCKED without toolchain/authorization)', () => {
	test('live authorization is explicit', () => {
		if (!authorized) {
			throw new Error(
				'BLOCKED: the P15c FastAPI journey requires CADDIE_LIVE_AUTHORIZED=1 (uv sync is a network ' +
					'effect). When authorized it probes uv/python/bun, then drives the REAL recipe flow ' +
					'(uv sync, uv run pytest, bun install, bun run build, uv run uvicorn app.main:app) and ' +
					'asserts a live API round trip. No toolchain is installed by this suite and nothing is mocked.',
			);
		}
		expect(authorized).toBe(true);
	});

	test(
		'the template installs, tests, builds and serves green (real uv toolchain)',
		async () => {
			if (!authorized) return; // gated above
			const missing = missingTools();
			if (missing.length > 0) {
				throw new Error(
					`BLOCKED: the P15c FastAPI journey needs ${missing.join(', ')} on PATH ` +
						'(or the contree sandbox image that carries them). Toolchains are never auto-installed.',
				);
			}

			const dir = mkdtempSync(join(tmpdir(), 'p15c-fastapi-'));
			try {
				cpSync(TEMPLATE, dir, { recursive: true });

				const install = run(['uv', 'sync'], dir);
				expect(install.code, install.output.slice(-1500)).toBe(0);
				expect(existsSync(join(dir, 'uv.lock')), 'uv.lock generated by the real resolve').toBe(true);

				const tests = run(['uv', 'run', 'pytest', '-q'], dir);
				expect(tests.code, tests.output.slice(-2500)).toBe(0);
				expect(tests.output).toMatch(/4 passed/);

				const clientInstall = run(['bun', 'install'], dir);
				expect(clientInstall.code, clientInstall.output.slice(-1500)).toBe(0);
				const build = run(['bun', 'run', 'build'], dir);
				expect(build.code, build.output.slice(-1500)).toBe(0);
				expect(existsSync(join(dir, 'client', 'dist', 'index.html')), 'built client shell').toBe(true);

				let server: ChildProcess | null = null;
				try {
					server = spawn('uv', ['run', 'uvicorn', 'app.main:app', '--port', String(PORT)], {
						cwd: dir,
						stdio: 'ignore',
					});
					const health = await waitForServer(`http://127.0.0.1:${PORT}/api/health`, 30_000);
					expect(health.status).toBe(200);
					expect(await health.json()).toEqual({ ok: true });

					const created = await fetch(`http://127.0.0.1:${PORT}/api/tasks`, {
						method: 'POST',
						headers: { 'content-type': 'application/json' },
						body: JSON.stringify({ title: 'prove the live API' }),
					});
					expect(created.status).toBe(201);
					const task = (await created.json()) as { id: number; title: string };
					expect(task.title).toBe('prove the live API');

					const listing = await fetch(`http://127.0.0.1:${PORT}/api/tasks`);
					const tasks = (await listing.json()) as Array<{ id: number }>;
					expect(tasks.some((entry) => entry.id === task.id)).toBe(true);
				} finally {
					server?.kill();
				}
			} finally {
				rmSync(dir, { recursive: true, force: true });
			}
		},
		900_000,
	);
});
